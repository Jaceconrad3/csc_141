# This program uses list slicing
# Uses heading to grab a specific part of the list
favorite_pizzas = ["buffalo chicken", "pepperoni", "meat lovers", "bbq chicken", "hot honey", "sausage", "cheese"]

print("The first three items in the list are:")
print(favorite_pizzas[:3])

print("Three items from the middle of the list are:")
print(favorite_pizzas[2:5])

print("The last three items in the list are:")
print(favorite_pizzas[-3:])
